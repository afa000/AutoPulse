import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import examples from '../../contracts/examples/diagnostic-api-examples.json' with { type: 'json' }

test('real diagnostic capture, manual records/correction, retry identity and advisory actions', async ({ page, request }, info) => {
  test.setTimeout(120_000)
  page.setDefaultTimeout(10_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const api = '/api/v1/vehicles/venue-2021'
  const get = async (part: string) => { const r = await request.get(`${api}/${part}`); expect(r.ok()).toBe(true); return r.json() }
  const screenshot = async (name: string) => {
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(name), fullPage: true })
  }
  await page.goto('/#/diagnostics')
  await expect(page.getByText(/No diagnostic snapshots accepted/)).toBeVisible()
  const snapshot = structuredClone(examples.snapshot)
  snapshot.bootId = '40000000-0000-4000-8000-000000000001'
  const post = async (sequence: number) => {
    snapshot.diagnosticSequence = sequence
    snapshot.capturedAt = new Date(Date.now() - 1000).toISOString()
    const r = await request.post('/api/v1/device/diagnostic-snapshots', { data: snapshot })
    expect(r.ok()).toBe(true)
    await expect.poll(async () => (await get('diagnostics')).processingState).toBe('CURRENT')
    await page.getByRole('button', { name: 'Refresh newest' }).click()
  }
  await post(0)
  await expect(page.getByText(/Complete empty read for this scope only/)).toHaveCount(3)
  snapshot.ecus[0].mil.illuminated = true
  const codes: string[] = snapshot.ecus[0].categories[1].codes
  codes.push('P0117', 'P1999')
  await post(1)
  await expect(page.getByRole('heading', { name: 'P0117 · CONFIRMED', exact: true })).toBeVisible()
  await expect(page.getByText(/Unknown definition/)).toBeVisible()
  await expect(page.getByText(/MIL: Reported on/)).toHaveCount(3)
  snapshot.ecus[0].outcome = 'PARTIAL'
  snapshot.ecus[0].categories[1].outcome = 'PARTIAL'
  snapshot.ecus[0].categories[1].codes = []
  await post(2)
  await expect(page.getByText(/No complete absence evidence/)).toHaveCount(1)
  await expect(page.getByText(/Complete empty read for this category only/)).toHaveCount(2)
  await expect(page.getByText(/PRESENT · current scope read PARTIAL/)).toHaveCount(2)
  await screenshot('diagnostics-desktop.png')
  await page.setViewportSize({ width: 390, height: 844 })
  await screenshot('diagnostics-narrow.png')
  await page.getByRole('link', { name: 'View evidence for P0117 · CONFIRMED · SIMULATOR' }).click()
  await expect(page.getByText('Recent transitions · newest first, at most 100')).toBeVisible()
  await page.getByText('Definition provenance', { exact: true }).click()
  await expect(page.locator('.evidence a').first()).toBeVisible()
  await screenshot('diagnostic-detail-narrow.png')

  await page.getByRole('link', { name: 'Maintenance', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Usage schedule')).toHaveValue('UNSET')
  await expect(page.getByLabel('Vehicle applicability')).toHaveValue('UNCONFIRMED')
  await page.getByLabel('Vehicle applicability').selectOption('US_2021_VENUE_G16')
  await page.getByLabel('Usage schedule').selectOption('NORMAL')
  await page.getByLabel('Calendar time zone (IANA)').fill('America/New_York')
  await page.getByLabel('I have confirmed').check()
  await page.getByRole('button', { name: 'Save profile', exact: true }).click()
  await expect(page.getByText(/Manual service profile · revision 1/)).toBeVisible()
  const record = async (p: Page, kind: string, at: string, odo: string) => {
    await p.getByRole('combobox', { name: 'Record kind', exact: true }).selectOption(kind)
    await p.getByLabel('Observed at (UTC)').fill(at)
    await p.getByLabel('Actual odometer value').fill(odo)
    await p.getByRole('button', { name: 'Save manual record', exact: true }).click()
  }
  const serviceTime = new Date(Date.now() - 60 * 86400_000).toISOString()
  await record(page, 'SERVICE', serviceTime, '10000')
  await expect(page.getByText(/Oil and filter schedule · UNKNOWN/)).toBeVisible()
  await expect(page.getByText(/^Reason: CURRENT_ODOMETER_UNKNOWN_OR_STALE/)).toBeVisible()
  // Forward the actual request to the backend, then lose only the acknowledgment.
  const bodies: string[] = []
  await page.route('**/maintenance-records', async route => {
    if (route.request().method() !== 'POST') return route.continue()
    bodies.push(route.request().postData()!)
    const saved = await route.fetch(); expect(saved.ok()).toBe(true)
    await route.abort('connectionfailed')
    await page.unroute('**/maintenance-records')
  })
  await record(page, 'ODOMETER', new Date(Date.now() - 2000).toISOString(), '18000')
  await expect(page.getByRole('button', { name: 'Retry identical submission' })).toBeVisible()
  expect((await get('maintenance-records')).items).toHaveLength(2)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Retry identical submission' })).toBeVisible()
  page.on('request', req => { if (req.method() === 'POST' && req.url().endsWith('/maintenance-records')) bodies.push(req.postData()!) })
  await page.getByRole('button', { name: 'Retry identical submission' }).click()
  await expect(page.getByRole('button', { name: 'Retry identical submission' })).toHaveCount(0)
  await expect(page.getByText(/Oil and filter schedule · DUE/)).toBeVisible()
  expect(bodies).toHaveLength(2); expect(bodies[1]).toBe(bodies[0])
  const records = await get('maintenance-records')
  expect(records.items).toHaveLength(2)
  const odometer = records.items.find((e: { kind: string }) => e.kind === 'ODOMETER')
  await page.getByRole('link', { name: `View history or correct record ${odometer.entryId}` }).click()
  await expect(page.getByRole('heading', { name: 'Correct manual record · revision 1' })).toBeVisible()
  await page.getByLabel('Actual odometer value').fill('18000.125')
  await page.getByLabel('Correction reason').fill('Corrected transcription from the manual reading')
  await page.getByRole('button', { name: 'Save correction' }).click()
  await expect(page.getByText(/Correct manual record · revision 2/)).toBeVisible()
  const corrected = await get(`maintenance-records/${odometer.entryId}`)
  expect(corrected.recentRevisions).toHaveLength(2)
  expect(corrected.item.odometerValue).toBe('18000.125')
  await screenshot('correction-narrow.png')
  await page.getByRole('link', { name: '← Back to Maintenance' }).click()
  await expect(page.getByRole('heading', { name: 'Record service or odometer', exact: true })).toBeVisible()
  await page.getByLabel('Observed at (UTC)').fill('not a UTC timestamp')
  await page.getByLabel('Actual odometer value').fill('18000.125')
  await page.getByRole('button', { name: 'Save manual record' }).click()
  await expect(page.getByRole('alert')).toContainText('Use a valid UTC timestamp')
  await screenshot('maintenance-validation-narrow.png')
  await page.getByRole('link', { name: 'View recommendations and actions' }).click()
  await expect.poll(async () => (await get('recommendations')).items.length).toBe(3)
  await page.getByRole('button', { name: 'Refresh newest' }).click()
  await expect(page.getByRole('heading', { name: 'DIAGNOSTIC · OPEN', exact: true })).toHaveCount(2)
  const recommendations = await get('recommendations')
  const diagnostic = recommendations.items.find((r: { kind: string }) => r.kind === 'DIAGNOSTIC')
  const oil = recommendations.items.find((r: { kind: string }) => r.kind === 'OIL_FILTER')
  await screenshot('recommendations-narrow.png')
  await page.getByRole('link', { name: `View evidence and actions for DIAGNOSTIC · ${diagnostic.id}` }).click()
  await page.getByText('Frozen rule evidence and provenance').click()
  await expect(page.getByText(/SIMULATED · synthetic diagnostic evidence/)).toBeVisible()
  await page.getByRole('button', { name: 'Acknowledge advisory' }).click()
  await expect(page.getByRole('heading', { name: 'DIAGNOSTIC · ACKNOWLEDGED', exact: true })).toBeVisible()
  await screenshot('advisory-narrow.png')
  await page.setViewportSize({ width: 1280, height: 900 })
  await screenshot('advisory-desktop.png')
  await page.getByRole('link', { name: 'Maintenance', exact: true }).click()
  await record(page, 'SERVICE', new Date(Date.now() - 500).toISOString(), '18000.125')
  await expect(page.getByText(/Oil and filter schedule · NOT_DUE/)).toBeVisible()
  await expect.poll(async () => (await get(`recommendations/${oil.id}`)).item.state).toBe('COMPLETED')
  expect((await get(`recommendations/${diagnostic.id}`)).item.state).toBe('ACKNOWLEDGED')
  await screenshot('maintenance-desktop.png')
  expect(errors).toEqual([])
  console.log('CARE_UI_EVIDENCE baselineUnknown=true completeEmpty+partial+known+unknown=true entries=3 revisions=4 ackLostRetryIdentical=true oilOnlyCompletion=true keyboard=true axe=0 desktop+narrow=true')
})
